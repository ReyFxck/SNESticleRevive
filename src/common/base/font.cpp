static Int32 _FontDrawChar(FontCharT *pFontChar, float fX, float fY, float z1, Uint32 uColor, int c)
{
	Uint32 u0,v0,u1,v1;
    Uint32 x0,y0,x1,y1;
    Int32 width, height;
    float sx, sy, px0, py0, px1, py1;

    width  = pFontChar->u1 - pFontChar->u0;
    height = pFontChar->v1 - pFontChar->v0;

    sx = GPPrimGetScaleX(); if (sx <= 0.0f) sx = 1.0f;
    sy = GPPrimGetScaleY(); if (sy <= 0.0f) sy = 1.0f;

    px0 = fX * sx + GPPrimGetOffsetX();
    py0 = fY * sy + GPPrimGetOffsetY();

    /*
     * At native 240p, place the source coordinates on texel centres and
     * finish the destination one GS subpixel after the final pixel centre.
     * This preserves every column of a 1:1 glyph without drawing a second
     * sprite over its right edge. UV and XY use 10.4/12.4 fixed point.
     */
    if (FONT_DRAW_SCALE == 1 && sx == 1.0f && sy == 1.0f)
    {
        u0 = (pFontChar->u0 << 4) + 8;  /* first texel centre */
        v0 = (pFontChar->v0 << 4) + 8;
        u1 = (pFontChar->u1 << 4) - 6;  /* 0.375 before the edge */
        v1 = (pFontChar->v1 << 4) - 6;

        px1 = px0 + (float)width  - 0.9375f;
        py1 = py0 + (float)height - 0.9375f;
    }
    else
    {
        /* Higher modes retain exact integer pixel scaling. */
        u0 = (pFontChar->u0 << 4);
        v0 = (pFontChar->v0 << 4);
        u1 = (pFontChar->u1 << 4);
        v1 = (pFontChar->v1 << 4);

        px1 = px0 + (float)(width  * FONT_DRAW_SCALE);
        py1 = py0 + (float)(height * FONT_DRAW_SCALE);
    }

    x0 = ((Uint32)FIXED4(px0)) & 0xFFFF;
    y0 = ((Uint32)FIXED4(py0)) & 0xFFFF;
    x1 = ((Uint32)FIXED4(px1)) & 0xFFFF;
    y1 = ((Uint32)FIXED4(py1)) & 0xFFFF;

	GPPrimTexRectAbs(x0, y0, u0, v0, x1, y1, u1, v1, 10, uColor, 1);

    /* advance in LOGICAL units: physical glyph width + 2px gap */
    return _FontAdvLogical(width * FONT_DRAW_SCALE + 2);

}

/* Bind the CJK PSMT4 atlas + resident VRAM palette.  gsKit emits TEX0
   with CBP/CPSM and CLD=LOAD per primitive, so the palette is fetched
   from VRAM without any per-frame upload.  LINEAR filtering: at 1:1
   sampling lands on texel centres (no blur), while the 240p 2:1 minify
   gets proper 2x2 averaging (the GS filters after CLUT lookup). */
static void _FontBindCjk(void)
{
    GPPrimSetTex(_Font_CjkTBP, CJK_ATLAS_W, CJK_ATLAS_LOG2, CJK_ATLAS_LOG2,
                 GS_PSMT4, _Font_CjkClutTBP, 0, GS_PSMCT32, 1);
}

/* Draw one 16x16 CJK glyph (atlas cell of glyph index iGlyph) at the
   logical position.  At 480i the glyph maps 1:1 texel->pixel (crisp
   HZK16 dot matrix); at 240p it is minified 2:1 with LINEAR sampling.
   Returns the logical advance (full-width slot, no gap). */
static Int32 _FontDrawCharCJK(Int32 iGlyph, float fX, float fY, Uint32 uColor)
{
    Uint32 u0, v0, u1, v1;
    Uint32 x0, y0, x1, y1;
    float sx, sy, px0, py0, px1, py1;
    Int32 tu, tv;
    Int32 disp;                 /* on-screen glyph size, physical pixels */

    tu = (iGlyph % CJK_CELLS_ROW) * CJK_GLYPH_SIZE;
    tv = (iGlyph / CJK_CELLS_ROW) * CJK_GLYPH_SIZE;

    sx = GPPrimGetScaleX(); if (sx <= 0.0f) sx = 1.0f;
    sy = GPPrimGetScaleY(); if (sy <= 0.0f) sy = 1.0f;

    px0 = fX * sx + GPPrimGetOffsetX();
    py0 = fY * sy + GPPrimGetOffsetY();

    /* Snap the origin to whole device pixels.  At 480i sx/sy are 2.5, so
       the raw origin is fractional and the GS (which interpolates ST from
       the sprite corner) would sample exactly on texel BOUNDARIES; with
       LINEAR filtering every column then blends 50/50 with its neighbour
       and each hanzi renders as a ghosted, unrecognisable shape.  After
       the snap the 1:1 path samples texel centres (crisp) and the 240p
       2:1 minify samples exact edges (clean 2x2 average).  The at most
       0.5px position shift is invisible. */
    px0 = (float)((Int32)(px0 + 0.5f));
    py0 = (float)((Int32)(py0 + 0.5f));

    /* 480i(2x): 16x16 texels -> 16x16 px = native 1:1.
       240p(1x): 16x16 texels -> 8x8 px (2:1, LINEAR-averaged). */
    disp = CJK_GLYPH_SIZE * FONT_DRAW_SCALE / 2;

    if (disp == CJK_GLYPH_SIZE)
    {
        /* Exact 1:1 over a snapped-integer origin.  The GS evaluates the
           interpolated UV at each pixel centre (x = x0 + k + 0.5), so to
           land sample k on the centre of texel tu+k the UV at the sprite
           edge must be the CELL EDGE (tu), NOT texel-centre (tu+0.5):
           adding the half-texel (+8) used to push every sample exactly
           onto a texel BOUNDARY, where LINEAR blends 50/50 with the
           neighbouring column and each hanzi renders as a ghosted,
           unrecognisable "wrong character".  Endpoint -15 keeps the UV
           slope at exactly 1.0 over the 15.0625 px span. */
        u0 = (tu << 4);
        v0 = (tv << 4);
        u1 = ((tu + CJK_GLYPH_SIZE) << 4) - 15;
        v1 = ((tv + CJK_GLYPH_SIZE) << 4) - 15;

        px1 = px0 + (float)CJK_GLYPH_SIZE - 0.9375f;
        py1 = py0 + (float)CJK_GLYPH_SIZE - 0.9375f;
    }
    else
    {
        /* Minify / integer upscale: plain texel->pixel mapping. */
        u0 = (tu << 4);
        v0 = (tv << 4);
        u1 = ((tu + CJK_GLYPH_SIZE) << 4);
        v1 = ((tv + CJK_GLYPH_SIZE) << 4);

        px1 = px0 + (float)disp;
        py1 = py0 + (float)disp;
    }

    x0 = ((Uint32)FIXED4(px0)) & 0xFFFF;
    y0 = ((Uint32)FIXED4(py0)) & 0xFFFF;
    x1 = ((Uint32)FIXED4(px1)) & 0xFFFF;
    y1 = ((Uint32)FIXED4(py1)) & 0xFFFF;

    GPPrimTexRectAbs(x0, y0, u0, v0, x1, y1, u1, v1, 10, uColor, 1);

    return _FontAdvLogical(disp);
}

Int32 FontGetStrWidth(const Char *pStr)
{
    Int32 iWidth = 0;
	FontT *pFont;
	pFont = _Font_State.pFont;
	if (!pFont) return 0;

    while (*pStr)
    {
        Uint32 cp;
        pStr = _FontNextCode(pStr, &cp);

        if (cp < 128)
        {
            if (cp != ' ')
            {
                FontCharT *pFontChar = &pFont->CharMap[cp];
                iWidth += _FontAdvLogical((pFontChar->u1 - pFontChar->u0) * FONT_DRAW_SCALE + 2);
            }
            else
            {
                // space
                iWidth += _FontAdvLogical(pFont->uCharX * FONT_DRAW_SCALE);
            }
        }
        else
        {
            /* CJK / unknown byte: full-width slot.  Monospace fonts
               advance two ASCII cells per hanzi; proportional fonts
               advance the on-screen glyph size. */
            Int32 adv = (pFont->uFixedWidth)
                        ? pFont->uFixedWidth * 2 * FONT_DRAW_SCALE
                        : CJK_GLYPH_SIZE * FONT_DRAW_SCALE / 2;
            iWidth += _FontAdvLogical(adv);
        }
    }
	return iWidth;
}


static void _FontDrawStr(FontT *pFont, Float32 vx, Float32 vy, Float32 vz, const Char *pStr, Uint32 uColor)
{
    TextureT *pTexture = &pFont->Texture;
    if (!pTexture) return;

    /* Bind ASCII atlas for the leading run; rebind on every CJK->ASCII
       transition so mixed text (e.g. "中文.sfc") renders correctly. */
    GPPrimSetTex(pTexture->uVramAddr, pTexture->uWidth,
                 pTexture->uWidthLog2, pTexture->uHeightLog2,
                 pTexture->eFormat, 0, 0, 0, 0);
    int bCjkBound = 0;

	while (*pStr)
	{
        Uint32 cp;
        pStr = _FontNextCode(pStr, &cp);

        if (cp < 128)
        {
            /* Re-bind ASCII atlas if we were on CJK (fixes garbled
               English/symbols after Chinese text). */
            if (bCjkBound)
            {
                GPPrimSetTex(pTexture->uVramAddr, pTexture->uWidth,
                             pTexture->uWidthLog2, pTexture->uHeightLog2,
                             pTexture->eFormat, 0, 0, 0, 0);
                bCjkBound = 0;
            }

            if (cp != ' ')
            {
                FontCharT *pFontChar = &pFont->CharMap[cp];
                Int32 iWidth;

                iWidth = _FontDrawChar(pFontChar, vx, vy, vz, uColor, (int)cp);

                if (pFont->uFixedWidth) iWidth = _FontAdvLogical((Int32)pFont->uFixedWidth * FONT_DRAW_SCALE);
			    vx += iWidth;
            }
            else
            {
		        vx += _FontAdvLogical(pFont->uCharX * FONT_DRAW_SCALE);
            }
        }
        else if (_Font_CjkReady)
        {
            Int32 iGlyph = _CjkFind(cp);
            if (iGlyph < 0) iGlyph = _Font_CjkTofu;    /* tofu box */
            if (iGlyph >= 0)
            {
                Int32 iWidth;

                _FontBindCjk();
                bCjkBound = 1;
                iWidth = _FontDrawCharCJK(iGlyph, vx, vy, uColor);

                /* CJK full-width slot advance */
                if (pFont->uFixedWidth)
                    iWidth = _FontAdvLogical((Int32)pFont->uFixedWidth * 2 * FONT_DRAW_SCALE);
                vx += iWidth;
            }
        }
        else
        {
            /* CJK data unavailable: still reserve a full-width slot so
               layout stays consistent. */
            vx += _FontAdvLogical(CJK_GLYPH_SIZE * FONT_DRAW_SCALE / 2);
        }
	}
}

static void _FontSetCharMap(FontT *pFont, Uint8 uChar, Uint32 u, Uint32 v, Uint32 w, Uint32 h)
{
	pFont->CharMap[uChar].u0 = u;
	pFont->CharMap[uChar].v0 = v;
	pFont->CharMap[uChar].u1 = u + w;
	pFont->CharMap[uChar].v1 = v + h;
}

static void _FontSetCharSize(FontT *pFont, Uint32 w, Uint32 h)
{
	pFont->uCharX = w;
	pFont->uCharY = h;
}

