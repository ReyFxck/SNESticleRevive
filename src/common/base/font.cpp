Uint32 FontGetVramSize()
{
    /* One block: UI RGBA8 atlas | CJK PSMT4 atlas | palette page.
       Both sub-offsets are 256B-aligned so CBP/CBP stay valid no matter
       where the video backend places the block. */
    return (Uint32)_FontTex_ui_w * (Uint32)_FontTex_ui_h * 4U   /* UI atlas */
         + CJK_ATLAS_BYTES                                      /* CJK atlas */
         + 8192U;                                               /* palette   */
}


void FontInit(Uint32 uVramAddr)
{
    CSurface Surface;

    // UI font (m5x7, Daniel Linssen): embedded RGBA8 atlas + explicit map.
    Surface.Set(_FontData_ui, _FontTex_ui_w, _FontTex_ui_h,
                _FontTex_ui_w * 4, PixelFormatGetByEnum(PIXELFORMAT_RGBA8));

    FontMakeFromMap(&_Font_Default, &Surface, uVramAddr,
                    _FontMap_ui, _FontMap_ui_count,
                    _Font_ui_spacew, _Font_ui_lineh);

    FontMakeFromMap(&_Font_Fixed, &Surface, uVramAddr,
                    _FontMap_ui, _FontMap_ui_count,
                    _Font_ui_spacew, _Font_ui_lineh);

    /* monospace cell = widest glyph so nothing overlaps in fixed mode */
    _Font_Fixed.uFixedWidth = _Font_ui_maxw;

    FontSetFont(0, &_Font_Default);
    FontSetFont(1, &_Font_Fixed);
    FontSetFont(2, &_Font_Default);
    FontSetFont(3, &_Font_Default);

	FontSelect(0);
	FontColor4f(1.0f, 1.0f, 1.0f, 1.0f);

    /* CJK atlas + resident palette live in the same allocation, right
       after the UI atlas (see FontGetVramSize). */
    _Font_CjkTBP     = uVramAddr + CJK_TEX_TBP_OFFSET;
    _Font_CjkClutTBP = uVramAddr + CJK_CLUT_TBP_OFFSET;

    TextureNew(&_Font_CjkTex, CJK_ATLAS_W, CJK_ATLAS_H, GS_PSMT4);
    TextureSetAddr(&_Font_CjkTex, _Font_CjkTBP);

    /* Expand the committed 1bpp source atlas directly to the exact PSMT4
       byte stream expected by the anyi renderer.  This keeps the same
       1024x1024 atlas/cell layout while avoiding a 5.4 MB generated C++
       source file. */
    {
        Uint32 i;
        for (i = 0; i < CJK_ATLAS_BYTES; i++)
        {
            Uint32 p0 = 2U * i;
            Uint32 p1 = p0 + 1U;
            Uint8 a = (Uint8)((_CjkBits[p0 >> 3] >> (7U - (p0 & 7U))) & 1U);
            Uint8 b = (Uint8)((_CjkBits[p1 >> 3] >> (7U - (p1 & 7U))) & 1U);
            s_CjkPack[i] = (Uint8)(a | (b << 4));
        }
    }

    /* Upload the 1024x1024 PSMT4 atlas as 256-line strips (128 KB each).
       gsKit's send helper takes the TBW in 64-pixel units regardless of
       the PSM and the GS BITBLT engine converts the linear stream into
       PSMT4 pages automatically. */
    {
        const Uint32 stripH     = 256;
        const Uint32 stripBytes = CJK_ATLAS_W * stripH / 2U;
        Uint32 i;
        for (i = 0; i * stripH < (Uint32)CJK_ATLAS_H; i++)
        {
            GPPrimUploadTexture(_Font_CjkTBP + i * (stripBytes / 256),
                                CJK_ATLAS_W, 0, 0, GS_PSMT4,
                                (void *)((Uint8 *)s_CjkPack + i * stripBytes),
                                CJK_ATLAS_W, stripH);
        }
    }

    /* 256-entry CT32 palette (1024 bytes) as a 256x1 image.  PSMT4 only
       indexes the first 16 entries (CSA=0); the remaining entries are
       harmless slack inside the reserved palette page. */
    GPPrimUploadTexture(_Font_CjkClutTBP, 256, 0, 0, GS_PSMCT32,
                        (void *)_CjkClut, 256, 1);

    _Font_CjkTofu   = _CjkFind(0x25A1);
    _Font_CjkReady  = (_Font_CjkTofu >= 0) ? TRUE : FALSE;
}

